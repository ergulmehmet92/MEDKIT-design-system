// Bundles the tokens and every component's CSS into dist/medkit.css, for pages without React or a
// bundler: link one file and use the class names shown in the docs.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const LEVELS = ["atoms", "molecules", "organisms", "templates"];

async function cssIn(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((e) => (e.isDirectory() ? cssIn(join(dir, e.name)) : e.name.endsWith(".css") ? [join(dir, e.name)] : [])));
  return nested.flat().sort();
}

// tokens.css sits in dist/tokens/, the bundle one level up, so its font paths lose a level.
const tokens = (await readFile(join(ROOT, "dist/tokens/tokens.css"), "utf8")).replaceAll("../../fonts/", "../fonts/");
const parts = [];
for (const level of LEVELS) {
  for (const file of await cssIn(join(ROOT, "components", level))) {
    parts.push(`/* ${relative(ROOT, file)} */\n${await readFile(file, "utf8")}`);
  }
}
const css = `/* MED·Kit, bundled. Generated by scripts/bundle-css.mjs; do not edit. */\n${tokens}\n${parts.join("\n")}`;
await writeFile(join(ROOT, "dist/medkit.css"), css);
console.log(`Bundled the tokens and ${parts.length} component stylesheets into dist/medkit.css (${Math.round(css.length / 1024)} KB)`);
